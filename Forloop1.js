/*
JS Program to display numbers from 1 to 10
*/
console.log("**********Forward loop***********")
for(let i=1; i<=10; i++){
    console.log(i);
}
console.log("**********Reverse loop***********")
for(let j=10; j>=1; j--){
    console.log(j);
}

console.log("**********Name 10times***********")
for(let k=1; k<=10; k++){
    console.log(`${k}.Harish`);
}
