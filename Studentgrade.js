/*
calculates a student's grade based on their marks using an if-else if ladder. 
Grade classification   Given a student's score (0–100), use if-else to print:
A if score ≥ 90
B if score ≥ 75
C if score ≥ 50
F otherwise
*/

let name= "Harish";
let score=92;

if(score >= 90 ){
    console.log(`${name} got grade A`);
}
else if(score>=75){
    console.log(`${name} got grade B`);
}
else if(score>=50){
    console.log(`${name}got grade C`);
}


